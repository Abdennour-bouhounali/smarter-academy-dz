def D(s):
    """Les décimaux du manuel (8,5 …) sont lus EXACTS, jamais un flottant."""
    return F(str(s).replace(',', '.'))


def fmt(q):
    """Écriture du manuel : virgule décimale (LaTeX `{,}`), fraction sinon."""
    q = F(q)
    if q.denominator == 1:
        return str(q.numerator)
    d = q.denominator
    while d % 2 == 0:
        d //= 2
    while d % 5 == 0:
        d //= 5
    if d == 1:
        s = f'{float(q):.10f}'.rstrip('0').rstrip('.')
        return s.replace('.', '{,}')
    return f'\\dfrac{{{q.numerator}}}{{{q.denominator}}}'


def counts(values):
    out = {}
    for v in values:
        out[v] = out.get(v, 0) + 1
    return dict(sorted(out.items()))


def cumul_up(freqs):
    s, out = 0, []
    for f in freqs:
        s += f
        out.append(s)
    return out


def cumul_down(freqs):
    return list(reversed(cumul_up(list(reversed(freqs)))))


def mean(values, freqs=None):
    freqs = freqs or [1] * len(values)
    return sum(F(v) * f for v, f in zip(values, freqs)) / sum(freqs)


def median(values):
    s = sorted(F(v) for v in values)
    n = len(s)
    return s[n // 2] if n % 2 else (s[n // 2 - 1] + s[n // 2]) / 2


def expand(values, freqs):
    return [v for v, f in zip(values, freqs) for _ in range(f)]


