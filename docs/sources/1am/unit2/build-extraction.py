import json
from decimal import Decimal as D
from pathlib import Path


def dec(s):
    return D(str(s).replace(',', '.'))


def fr(x):
    """Un décimal écrit comme le manuel : virgule décimale, sans zéros inutiles."""
    x = D(x).normalize()
    s = format(x, 'f')
    return s.replace('.', ',')


def hm(h, m, s=None):
    return (h * 3600 + m * 60 + (s or 0))


def hms(t, seconds=False):
    h, r = divmod(t, 3600)
    m, s = divmod(r, 60)
    return f'{h} h {m} min' + (f' {s} s' if seconds else '')


