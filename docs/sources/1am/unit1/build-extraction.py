def dec(s):
    return D(str(s).replace(',', '.'))


def fr(x):
    """Un décimal écrit comme le manuel : virgule décimale, sans zéros inutiles."""
    x = D(x).normalize()
    return format(x, 'f').replace('.', ',')


def spaced(n):
    """L'écriture par classes de trois chiffres, séparées par une espace (manuel p. 11)."""
    s = str(n)
    out = []
    while s:
        out.insert(0, s[-3:])
        s = s[:-3]
    return ' '.join(out)


# ── Écriture en lettres (convention de la plateforme, voir `discrepancies` › words) ────────────────────────────
ONES = ['', 'واحد', 'اثنان', 'ثلاثة', 'أربعة', 'خمسة', 'ستة', 'سبعة', 'ثمانية', 'تسعة']
TEENS = {10: 'عشرة', 11: 'أحد عشر', 12: 'اثنا عشر'}
TENS = ['', '', 'عشرون', 'ثلاثون', 'أربعون', 'خمسون', 'ستون', 'سبعون', 'ثمانون', 'تسعون']
HUNDREDS = ['', 'مائة', 'مائتان', 'ثلاثمائة', 'أربعمائة', 'خمسمائة', 'ستمائة', 'سبعمائة', 'ثمانمائة', 'تسعمائة']
SCALES = [  # (singulier, duel, pluriel 3–10, accusatif 11–99)
    None,
    ('ألف', 'ألفان', 'آلاف', 'ألفا'),
    ('مليون', 'مليونان', 'ملايين', 'مليونا'),
    ('مليار', 'ملياران', 'ملايير', 'مليارا'),
]


def below100(n):
    if n < 10:
        return ONES[n]
    if n in TEENS:
        return TEENS[n]
    if n < 20:
        return f'{ONES[n - 10]} عشر'
    t, u = divmod(n, 10)
    return TENS[t] if u == 0 else f'{ONES[u]} و{TENS[t]}'


def below1000(n, construct=False):
    h, r = divmod(n, 100)
    parts = []
    if h:
        # « مائتا ألف » : le duel en construction devant un nom de classe, quand rien ne suit.
        parts.append('مائتا' if (h == 2 and r == 0 and construct) else HUNDREDS[h])
    if r:
        parts.append(below100(r))
    return ' و'.join(parts)


def class_words(n, k):
    """n (1..999) unités de la classe k (1 = آلاف, 2 = ملايين, 3 = ملايير)."""
    sing, dual, plur, acc = SCALES[k]
    if n == 1:
        return sing
    if n == 2:
        return dual
    r = n % 100
    if n < 100:
        return f'{below100(n)} {plur if n <= 10 else acc}'
    head = below1000(n, construct=True)
    if r == 0 or r in (1, 2):
        return f'{head} {sing}'
    return f'{head} {plur if r <= 10 else acc}'


def words(n):
    """Un entier naturel en lettres (0 ≤ n < 10¹²)."""
    assert 0 <= n < 10 ** 12
    if n == 0:
        return 'صفر'
    groups = []
    k = 0
    while n:
        n, g = divmod(n, 1000)
        if g:
            groups.insert(0, below1000(g) if k == 0 else class_words(g, k))
        k += 1
    return ' و'.join(groups)


