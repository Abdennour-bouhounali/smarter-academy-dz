def digits_by_rank(n):
    """{rang: chiffre} d'un entier : 0 = الآحاد, 1 = العشرات, …"""
    return {k: int(c) for k, c in enumerate(reversed(str(n)))}


def count_of_rank(n, k):
    """« عدد العشرات » etc. : le nombre d'unités de rang 10^k contenues dans n."""
    return n // 10 ** k


def decompose(n):
    """Le مفكوك d'un entier : « 6 × 1000 + 3 × 100 + 9 × 10 + 2 » (rangs nuls omis)."""
    terms = []
    for k, d in sorted(digits_by_rank(n).items(), reverse=True):
        if d == 0:
            continue
        terms.append(str(d) if k == 0 else f'{d} × {10 ** k}')
    return ' + '.join(terms)


RANK_AR = ['الآحاد', 'العشرات', 'المئات', 'الآلاف', 'عشرات الآلاف', 'مئات الآلاف', 'الملايين', 'عشرات الملايين', 'مئات الملايين', 'الملايير']
DEC_RANK_AR = ['الأعشار (الأجزاء من عشرة)', 'الأجزاء من مائة', 'الأجزاء من ألف']


def ranks_of_decimal(s):
    """Le rang de chaque chiffre d'une écriture décimale « 6392,459 » : [(chiffre, rang), …] de gauche à droite."""
    ip, _, dp = s.partition(',')
    out = [(int(c), RANK_AR[len(ip) - 1 - i]) for i, c in enumerate(ip)]
    out += [(int(c), DEC_RANK_AR[i]) for i, c in enumerate(dp)]
    return out


