def dec(s):
    return D(str(s).replace(',', '.'))


def fr(x):
    x = D(x).normalize()
    return format(x, 'f').replace('.', ',')


def euclid(a, b):
    q, r = divmod(a, b)
    return {'q': q, 'r': r, 'eq': f'{a} = {b} × {q} + {r}'}


