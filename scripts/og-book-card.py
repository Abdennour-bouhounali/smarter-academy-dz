#!/usr/bin/env python3
"""Share card (1200x630) of a printed book: its REAL cover on one side, the title on the other.

Reuses the helpers of og-card.py (Cairo + raqm shaping, brand gradient) — see the "OG share cards" section
of CLAUDE.md. Deterministic; nothing is generated by a model.

    python3 scripts/og-book-card.py apps/web/public/images/books/smart-protocol/front-cover.webp \
        "بروتوكول SMART لحل المسائل الرياضية" --eyebrow "كتاب مطبوع · بكالوريا الرياضيات" \
        -o apps/web/public/og/smart-protocol.png
"""
import argparse
import importlib.util
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

spec = importlib.util.spec_from_file_location("ogcard", Path(__file__).with_name("og-card.py"))
og = importlib.util.module_from_spec(spec)
spec.loader.exec_module(og)

W, H, SS = og.W, og.H, og.SS


def main():
    p = argparse.ArgumentParser()
    p.add_argument("cover")
    p.add_argument("title")
    p.add_argument("--eyebrow", default="")
    p.add_argument("--footer", default="Smarter Academy")
    p.add_argument("--theme", default="blue", choices=sorted(og.THEMES))
    p.add_argument("-o", "--output", required=True)
    a = p.parse_args()

    base, accent, glow = og.THEMES[a.theme]
    img = og.gradient_bg(base, accent, glow)

    # Cover on the left, with a soft shadow.
    cover = Image.open(a.cover).convert("RGB")
    ch = 520 * SS
    cover = cover.resize((round(cover.width * ch / cover.height), ch), Image.LANCZOS)
    cx, cy = 86 * SS, (H * SS - ch) // 2
    shadow = Image.new("RGBA", img.size, (0, 0, 0, 0))
    ImageDraw.Draw(shadow).rectangle([cx + 10 * SS, cy + 16 * SS, cx + cover.width + 10 * SS, cy + ch + 16 * SS], fill=(0, 0, 0, 150))
    shadow = shadow.filter(ImageFilter.GaussianBlur(18 * SS))
    img = Image.alpha_composite(img.convert("RGBA"), shadow).convert("RGB")
    img.paste(cover, (cx, cy))

    d = ImageDraw.Draw(img)
    right = (W - 80) * SS
    left_limit = cx + cover.width + 60 * SS
    max_w = right - left_limit

    font = og.fit_font(d, a.title, max_w, start=76, floor=48)
    lines = og.balanced_wrap(d, a.title, font, max_w)
    line_h = int(font.size * 1.3)
    eyebrow_font = og.load("regular", 30)
    total = line_h * len(lines) + (50 * SS if a.eyebrow else 0)
    y = (H * SS - total) // 2 - 20 * SS

    if a.eyebrow:
        og.draw_text(d, (right, y), a.eyebrow, eyebrow_font, tuple(min(255, c + 90) for c in accent), "ra")
        y += 56 * SS
    for line in lines:
        og.draw_text(d, (right, y), line, font, og.CREAM, "ra")
        y += line_h
    y += 34 * SS
    d.rounded_rectangle([right - 150 * SS, y, right, y + 8 * SS], radius=4 * SS, fill=accent)
    og.draw_text(d, (right, H * SS - 64 * SS), a.footer, og.load("bold", 32), og.MUTED, "rs")

    img = img.resize((W, H), Image.LANCZOS)
    Path(a.output).parent.mkdir(parents=True, exist_ok=True)
    img.save(a.output, optimize=True)
    print(f"Saved {a.output} ({W}x{H})")


if __name__ == "__main__":
    main()
