#!/usr/bin/env node
/**
 * « مختبر التفكير » — construit content/thinking-lab/index.generated.json, le SEUL
 * fichier de contenu que lit le serveur (ChallengeRepository, phase 1), comme
 * ExerciseRepository lit content/practice/index.generated.json.
 *
 * L'index contient les défis `published`, complets (réponse comprise : il ne
 * quitte jamais le serveur — aucun module web ne l'importe), triés par numéro.
 *
 *   node scripts/build-thinking-lab-index.mjs          écrit l'index
 *   node scripts/build-thinking-lab-index.mjs --check  échoue si l'index est périmé
 *
 * validate-thinking-lab.mjs --strict refait la même comparaison (check:lessons).
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const CONTENT_ROOT = process.env.SMARTER_THINKING_LAB_ROOT || join(repoRoot, 'content/thinking-lab');
export const CHALLENGES_DIR = join(CONTENT_ROOT, 'challenges');
export const INDEX_PATH = join(CONTENT_ROOT, 'index.generated.json');

/** @returns {{file: string, data?: object, error?: string}[]} les fichiers de défis, dans l'ordre des noms */
export function readChallenges(dir = CHALLENGES_DIR) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((file) => {
      try {
        return { file, data: JSON.parse(readFileSync(join(dir, file), 'utf-8')) };
      } catch (e) {
        return { file, error: `JSON illisible : ${e.message}` };
      }
    });
}

/** Le texte exact de l'index pour ces défis (déterministe). */
export function serializeIndex(entries) {
  const challenges = entries
    .filter((e) => e.data?.status === 'published')
    .map(({ data }) => Object.fromEntries(Object.entries(data).filter(([k]) => k !== '$schema')))
    .sort((a, b) => a.number - b.number);
  const index = {
    $comment: 'GENERATED by scripts/build-thinking-lab-index.mjs from content/thinking-lab/challenges/ — do not edit. Server-only (holds the answers). Contract: docs/architecture/THINKING_LAB.md.',
    count: challenges.length,
    challenges,
  };
  return `${JSON.stringify(index, null, 2)}\n`;
}

export function indexIsFresh(entries = readChallenges()) {
  return existsSync(INDEX_PATH) && readFileSync(INDEX_PATH, 'utf-8') === serializeIndex(entries);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const entries = readChallenges();
  if (process.argv.includes('--check')) {
    if (!indexIsFresh(entries)) {
      console.error('content/thinking-lab/index.generated.json est périmé — relance `npm run build:thinking-lab-index`');
      process.exit(1);
    }
    console.log('thinking-lab index: à jour');
  } else {
    writeFileSync(INDEX_PATH, serializeIndex(entries));
    console.log(`thinking-lab index: ${entries.filter((e) => e.data?.status === 'published').length} défi(s) publié(s) écrit(s)`);
  }
}
