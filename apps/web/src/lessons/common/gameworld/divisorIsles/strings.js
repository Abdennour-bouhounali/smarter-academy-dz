/**
 * « أرخبيل القواسم » — every sentence of the game (Arabic, the platform's own wording; nothing is quoted from the textbook).
 * A rule is NAMED only on a « لوح المعرفة » that opens AFTER the student has seen it happen in the world.
 */
/** Arabic number agreement: « لوح واحد », « لوحان », « 5 ألواح », « 21 لوحًا ». */
export const planks = (q) => (q === 1 ? 'لوح واحد' : q === 2 ? 'لوحان' : q >= 3 && q <= 10 ? `${q} ألواح` : `${q} لوحًا`);
const cells = (r) => (r === 1 ? 'خانة واحدة فارغة' : r === 2 ? 'خانتان فارغتان' : r >= 3 && r <= 10 ? `${r} خانات فارغة` : `${r} خانة فارغة`);

const div = (a, b) => ({ q: Math.floor(a / b), r: a % b });

/** The sentence of a practice wave (shown big above the rail). `$…$` is maths. */
export function waveSay(w) {
  switch (w.type) {
    case 'divisorOf': case 'sureOf': case 'fromProduct': return `قاسم للعدد ${w.a}`;
    case 'divides': return `عدد يقسم ${w.a}`;
    case 'multipleOf': return `مضاعف للعدد ${w.b}`;
    case 'divisibleBy': return `عدد يقبل القسمة على ${w.b}`;
    case 'remainder': return `باقي قسمة ${w.a} على ${w.b}`;
    case 'missing': return `$${w.a} = ${w.b} \\times \\square$`;
    case 'everyNumber': return 'قاسم لكلّ عدد طبيعي';
    case 'biggest': return `أكبر قاسم للعدد ${w.a}`;
    case 'smallest': return `أصغر قاسم للعدد ${w.a}`;
    default: return w.say ?? '';
  }
}
/** A line above the sentence, when the wave gives something to read first (the product of « اقرأ الجداء »). */
export const waveHint = (w) => (w.type === 'fromProduct' ? `$${w.a} = ${w.b} \\times ${w.q}$` : null);

/**
 * Guidance after a wrong gate: WHY the chosen number does not fit (with its own division), then why the right one does.
 * Always the world's reasoning — a remainder, a product — never « wrong » alone.
 */
export function explain(w, n) {
  const g = w.gates[w.good];
  const zero = '0 ليس قاسمًا لأيّ عدد: لا نقسم على 0.';
  const notDivisor = (a, x) => {
    if (x === 0) return zero;
    if (x > a && x % a === 0) return `${x} مضاعف للعدد ${a}، وليس قاسمًا له: القاسم لا يكون أكبر من العدد.`;
    const { q, r } = div(a, x);
    return `$${a} = ${x} \\times ${q} + ${r}$: الباقي ${r}، إذن ${x} ليس قاسمًا للعدد ${a}.`;
  };
  const isDivisor = (a, x) => (x === 1 ? `1 قاسم لكلّ عدد طبيعي: $${a} = 1 \\times ${a}$.` : x === a ? `كلّ عدد غير معدوم قاسم لنفسه: $${a} = ${a} \\times 1$.` : `$${a} = ${x} \\times ${a / x}$: الباقي 0، إذن ${x} قاسم للعدد ${a}.`);
  switch (w.type) {
    case 'divisorOf': case 'divides': case 'sureOf': case 'fromProduct':
      return { wrong: notDivisor(w.a, n), right: isDivisor(w.a, g) };
    case 'multipleOf': case 'divisibleBy': {
      let wrong;
      if (n === 0) wrong = zero;
      else if (n < w.b && w.b % n === 0) wrong = `${n} قاسم للعدد ${w.b}، وليس مضاعفًا له: مضاعفات ${w.b} هي ${w.b}، ${2 * w.b}، ${3 * w.b}…`;
      else { const { q, r } = div(n, w.b); wrong = `$${n} = ${w.b} \\times ${q} + ${r}$: الباقي ${r}، إذن ${n} لا يقبل القسمة على ${w.b}.`; }
      return { wrong, right: `$${g} = ${w.b} \\times ${g / w.b}$: ${g} مضاعف للعدد ${w.b}، أي يقبل القسمة عليه.` };
    }
    case 'remainder':
      return { wrong: `تحقّق: $${w.b} \\times ${w.q} + ${n} = ${w.b * w.q + n}$، وليس ${w.a}.`, right: `$${w.a} = ${w.b} \\times ${w.q} + ${w.r}$: الباقي ${w.r}.` };
    case 'missing':
      return { wrong: `$${w.b} \\times ${n} = ${w.b * n}$، وليس ${w.a}.`, right: `$${w.a} = ${w.b} \\times ${w.q}$: العددان ${w.b} و ${w.q} قاسمان للعدد ${w.a}.` };
    case 'everyNumber':
      return { wrong: n === 0 ? zero : `${n} ليس قاسمًا لكلّ عدد: $${n + 1} = ${n} \\times 1 + 1$، الباقي 1.`, right: '1 قاسم لكلّ عدد طبيعي: $a = 1 \\times a$.' };
    case 'biggest':
      return {
        wrong: n > w.a ? `${n} أكبر من ${w.a}: هو مضاعف له، والقاسم لا يتجاوز العدد.` : w.a % n === 0 ? `${n} قاسم للعدد ${w.a} فعلًا، لكنّه ليس الأكبر.` : notDivisor(w.a, n),
        right: `أكبر قاسم للعدد ${w.a} هو ${w.a} نفسه: $${w.a} = ${w.a} \\times 1$.`,
      };
    case 'smallest':
      return {
        wrong: n === 0 ? zero : w.a % n === 0 ? `${n} قاسم للعدد ${w.a} فعلًا، لكنّه ليس الأصغر.` : notDivisor(w.a, n),
        right: `أصغر قاسم لأيّ عدد هو 1: $${w.a} = 1 \\times ${w.a}$.`,
      };
    default: return { wrong: '', right: '' };
  }
}

